import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import { bukmarkDark, bukmarkLight } from './src/code-themes.mjs';
import { packagingFiles } from './src/packaging.mjs';

export default defineConfig({
  site: 'https://bukmark.it',
  // Fetch a page as soon as its link scrolls into view. The docs are a handful
  // of small static pages, so this is cheap, and a click lands on a page that
  // is already in cache. No view transition on top: cross-fading the old page
  // into the new one showed both at once, which read as a flicker. The browser
  // keeps the old page up until the new one paints, and the header and
  // sidebar paint the same, so only the content changes.
  prefetch: { prefetchAll: true, defaultStrategy: 'viewport' },
  integrations: [
    starlight({
      title: 'bukmark',
      logo: { src: './public/logo-mark.svg', alt: 'bukmark' },
      favicon: '/favicon.svg',
      description:
        'Self-hosted bookmark manager built around triage. Capture in one click; sorting is a separate, deliberate pass.',
      social: [
        { icon: 'github', label: 'GitHub', href: 'https://github.com/xooxoxxo/bukmark' },
      ],
      customCss: ['./src/styles/custom.css'],
      // Fetched with the page rather than found later inside the stylesheet,
      // so the first paint already has them (see the @font-face rules).
      head: ['bricolage-grotesque-latin', 'geist-latin'].map((font) => ({
        tag: 'link',
        attrs: { rel: 'preload', href: `/fonts/${font}.woff2`, as: 'font', type: 'font/woff2', crossorigin: '' },
      })),
      // Share images and titles for every docs page (src/og/, src/pages/og/).
      routeMiddleware: './src/routeData.ts',
      expressiveCode: {
        themes: [bukmarkDark, bukmarkLight],
        // 'code', not the default 'auto': 'auto' gives shell languages a fake
        // terminal frame -- titlebar and three traffic-light dots -- which is
        // re-drawn chrome design.md rules out. 'none' looks like the right
        // value but is ignored for shell blocks; 'code' drops the titlebar and
        // keeps the copy button.
        //
        // Colours come from the themes above, never styleOverrides with
        // var(--bk-*): those feed Expressive Code's colour maths and silently
        // stop it emitting the rules that colour syntax tokens.
        // Wrap rather than scroll: a docs reader should see the whole command
        // and its trailing comment without dragging a scrollbar.
        defaultProps: { frame: 'code', wrap: true },
      },
      // The landing page at / is ours, not Starlight's.
      disable404Route: false,
      // Autogenerated, not an explicit slug list: this task creates only the
      // index page, and Starlight fails the build when a sidebar entry names a
      // page that does not exist yet. Ordering comes from each page's
      // `sidebar.order` frontmatter in Tasks 2 and 3.
      sidebar: [
        {
          label: 'Documentation',
          items: [{ autogenerate: { directory: 'docs' } }],
        },
      ],
    }),
    // dist/install.sh and dist/bukmark, from packaging/ (src/packaging.mjs).
    packagingFiles(),
  ],
});
